import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const source=await readFile('dist/room-tools.js','utf8');
const pure=source.slice(source.indexOf('export function totalCost'),source.indexOf('\nconst $=')).replaceAll('export ','');
const context=vm.createContext({});vm.runInContext(pure,context);
assert.equal(context.totalCost({price:100,delivery:20,assembly:30},8),158);
assert.equal(context.totalCost({price:100,delivery:'',assembly:''},0),100);
assert.match(context.fitCheck({width:80,depth:30,height:35},{width:70,depth:40}),/exceeds/);
assert.match(context.fitCheck({width:80,depth:30,height:35},{width:100,depth:100,door:25}),/Access warning/);
assert.match(context.fitCheck({width:40,depth:60,height:25},{width:70,depth:50}),/Footprint fits/);
assert.match(context.fitCheck({},{width:70,depth:50}),/Add all/);
const board={items:[{id:'a',name:'Desk',price:100}],people:['Me'],budget:500,tax:8};
assert.equal(context.validateBoard(board),true);
assert.equal(context.validateBoard({...board,tax:-1}),false);
assert.equal(context.validateBoard({...board,people:['__proto__']}),false);
assert.equal(context.validateBoard({...board,items:[{id:'a',name:'Bad',price:-3}]}),false);
const worker=await readFile('dist/matcher-worker.js','utf8');
assert.ok(worker.includes('score:score/count'));
const html=await readFile('dist/index.html','utf8');assert.ok(html.includes('room-tools.js'));assert.ok(html.includes('room-tools.css'));
const photo=await readFile('dist/photo.js','utf8');assert.ok(photo.includes('images:photos'));assert.ok(photo.includes('data-save='));
console.log('Passed: total costs, room/access checks, board validation, multi-image and save wiring.');
